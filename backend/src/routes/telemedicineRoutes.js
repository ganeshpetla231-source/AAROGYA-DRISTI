const express = require('express');
const { authenticate, authorize } = require('../middleware/authMiddleware');
const controller = require('../controllers/telemedicineController');
const router = express.Router();
router.use(authenticate);
router.get('/config', authorize('patient', 'doctor'), controller.config);
router.get('/availability', authorize('patient', 'doctor'), controller.availability);
router.post('/availability', authorize('doctor'), controller.createAvailability);
router.delete('/availability/:id', authorize('doctor'), controller.removeAvailability);
router.get('/appointments', authorize('patient', 'doctor'), controller.appointments);
router.get('/admin/overview', authorize('admin'), controller.adminOverview);
router.post('/appointments/clinic', authorize('patient'), controller.bookClinic);
router.post('/appointments', authorize('patient'), controller.book);
router.post('/appointments/:id/consent', authorize('patient', 'doctor'), controller.consent);
router.get('/appointments/:id/room', authorize('patient', 'doctor'), controller.room);
router.patch('/appointments/:id/confirm', authorize('doctor'), (req, res, next) => { req.params.action = 'confirm'; next(); }, controller.action);
router.patch('/appointments/:id/decline', authorize('doctor'), (req, res, next) => { req.params.action = 'decline'; next(); }, controller.action);
router.patch('/appointments/:id/cancel', authorize('patient', 'doctor'), (req, res, next) => { req.params.action = 'cancel'; next(); }, controller.action);
router.patch('/appointments/:id/reschedule', authorize('patient', 'doctor'), (req, res, next) => { req.params.action = 'reschedule'; next(); }, controller.action);
router.patch('/appointments/:id/notes', authorize('doctor'), controller.notes);
router.get('/appointments/:id/prescriptions', authorize('patient', 'doctor'), controller.prescriptions);
router.post('/appointments/:id/prescriptions', authorize('doctor'), controller.createPrescription);
router.post('/appointments/:id/follow-ups', authorize('doctor'), controller.followup);
module.exports = router;
