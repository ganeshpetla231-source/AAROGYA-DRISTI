const express = require('express');
const cors = require('cors');
const helmet = require('helmet');
const { apiLimiter } = require('./middleware/rateLimits');
const { corsOptions } = require('./config/security');
const healthRoutes = require('./routes/healthRoutes');
const resourceRoutes = require('./routes/resourceRoutes');
const authRoutes = require('./routes/authRoutes');
const patientQrRoutes = require('./routes/patientQrRoutes');
const voiceTranscriptRoutes = require('./routes/voiceTranscriptRoutes');
const clinicalRoutes = require('./routes/clinicalRoutes');
const telemedicineRoutes = require('./routes/telemedicineRoutes');
const notificationRoutes = require('./routes/notificationRoutes');
const analyticsRoutes = require('./routes/analyticsRoutes');
const educationRoutes = require('./routes/educationRoutes');
const healthcareWorkerRoutes = require('./routes/healthcareWorkerRoutes');
const assistantRoutes = require('./routes/assistantRoutes');
const governmentDirectoryRoutes = require('./routes/governmentDirectoryRoutes');
const adminRoutes = require('./routes/adminRoutes');
const facilityRoutes = require('./routes/facilityRoutes');
const adminFacilitiesRoutes = require('./routes/adminFacilitiesRoutes');
const errorMiddleware = require('./middleware/errorMiddleware');

const app = express();
app.disable('x-powered-by');
if (process.env.NODE_ENV === 'production') app.set('trust proxy', 1);
app.use(helmet());
app.use(cors(corsOptions()));
app.use(express.json({ limit: '1mb' }));
app.use('/api', apiLimiter);
app.use('/api/health', healthRoutes);
app.use('/api/auth', authRoutes);
app.use('/api/admin', adminRoutes);
app.use('/api/facility', facilityRoutes);
app.use('/api/facilities', adminFacilitiesRoutes);
app.use('/api/patient-qr', patientQrRoutes);
app.use('/api/education', educationRoutes);
app.use('/api/healthcare-workers', healthcareWorkerRoutes);
app.use('/api/assistant', assistantRoutes);
app.use('/api/government-directory', governmentDirectoryRoutes);
app.use('/api', voiceTranscriptRoutes);
app.use('/api/clinical', clinicalRoutes);
app.use('/api/telemedicine', telemedicineRoutes);
app.use('/api/notifications', notificationRoutes);
app.use('/api/analytics', analyticsRoutes);
app.use('/api', resourceRoutes);
app.use((req, res) => res.status(404).json({ status: 'error', message: 'Route not found' }));
app.use(errorMiddleware);

module.exports = app;
